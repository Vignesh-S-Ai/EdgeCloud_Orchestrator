#!/bin/bash
# =============================================================================
# 00-collect-outputs.sh — Collect all rebuild values from Terraform + AWS CLI
# =============================================================================
# PURPOSE: Generate rebuild.env from current Terraform state and AWS account
# INPUTS: Terraform state, AWS CLI access
# OUTPUTS: rebuild.env (or stdout)
# DESTRUCTIVE: No
# SAFE: Yes
# REQUIRES_MANUAL_STEP: No
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REBUILD_DIR="$(dirname "$SCRIPT_DIR")"
ENV_FILE="${REBUILD_DIR}/rebuild.env"

echo "=== Collecting rebuild values ==="

# --- AWS Account ---
AWS_ACCOUNT_ID=$(aws sts get-caller-identity --query Account --output text 2>/dev/null || echo "<FAILED>")
AWS_REGION=$(aws configure get region 2>/dev/null || echo "ap-south-1")
AWS_PROFILE=$(aws configure get profile 2>/dev/null || echo "edgecloud")

# --- Terraform Outputs ---
TF_DIR="${REBUILD_DIR}/../../terraform-new"
if [ -d "$TF_DIR" ]; then
  cd "$TF_DIR"
  CLOUD_PUBLIC_IP=$(terraform output -raw ec2_public_ip 2>/dev/null || echo "<RUN_TERRAFORM_OUTPUT>")
  CLOUD_INSTANCE_ID=$(terraform output -raw ec2_instance_id 2>/dev/null || echo "<RUN_TERRAFORM_OUTPUT>")
  EDGE_PUBLIC_IP=$(terraform output -raw edge_node_public_ip 2>/dev/null || echo "<RUN_TERRAFORM_OUTPUT>")
  EDGE_INSTANCE_ID=$(terraform output -raw edge_node_instance_id 2>/dev/null || echo "<RUN_TERRAFORM_OUTPUT>")
  cd "$SCRIPT_DIR"
else
  echo "WARNING: Terraform directory not found at $TF_DIR"
  CLOUD_PUBLIC_IP="<MANUAL>"
  CLOUD_INSTANCE_ID="<MANUAL>"
  EDGE_PUBLIC_IP="<MANUAL>"
  EDGE_INSTANCE_ID="<MANUAL>"
fi

# --- Derived values ---
ECR_REGISTRY="${AWS_ACCOUNT_ID}.dkr.ecr.${AWS_REGION}.amazonaws.com"

# --- Private IPs (auto-derived; fall back to <MANUAL> if instance IDs unknown) ---
CLOUD_PRIVATE_IP=$(aws ec2 describe-instances --instance-ids "${CLOUD_INSTANCE_ID}" \
  --query 'Reservations[0].Instances[0].PrivateIpAddress' --output text \
  --region "${AWS_REGION}" --profile "${AWS_PROFILE}" 2>/dev/null || echo "<MANUAL>")
EDGE_PRIVATE_IP=$(aws ec2 describe-instances --instance-ids "${EDGE_INSTANCE_ID}" \
  --query 'Reservations[0].Instances[0].PrivateIpAddress' --output text \
  --region "${AWS_REGION}" --profile "${AWS_PROFILE}" 2>/dev/null || echo "<MANUAL>")

# --- Node names ---
CLOUD_NODE_NAME=$(aws ec2 describe-instances --instance-ids "${CLOUD_INSTANCE_ID}" \
  --query 'Reservations[0].Instances[0].PrivateDnsName' --output text \
  --region "${AWS_REGION}" --profile "${AWS_PROFILE}" 2>/dev/null || echo "<MANUAL>")

echo ""
echo "=== Generated rebuild.env ==="
cat <<EOF
# Generated by 00-collect-outputs.sh on $(date -u)
AWS_REGION=${AWS_REGION}
AWS_PROFILE=${AWS_PROFILE}
PROJECT_NAME=edgecloud
AWS_ACCOUNT_ID=${AWS_ACCOUNT_ID}
CLOUD_PUBLIC_IP=${CLOUD_PUBLIC_IP}
CLOUD_PRIVATE_IP=${CLOUD_PRIVATE_IP}
CLOUD_INSTANCE_ID=${CLOUD_INSTANCE_ID}
EDGE_PUBLIC_IP=${EDGE_PUBLIC_IP}
EDGE_PRIVATE_IP=${EDGE_PRIVATE_IP}
EDGE_INSTANCE_ID=${EDGE_INSTANCE_ID}
ECR_REGISTRY=${ECR_REGISTRY}
KUBEEDGE_VERSION=v1.23.1
K3S_VERSION=v1.32.13+k3s1
EDGE_NODE_NAME=edge-ec2-node
CLOUD_NODE_NAME=${CLOUD_NODE_NAME}
EDGE_NAMESPACE=edgecloud
EOF

echo ""
echo "To save: bash $0 > ${ENV_FILE}"
echo "Then edit ${ENV_FILE} to fill in <MANUAL> values."
